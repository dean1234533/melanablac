DROP TABLE IF EXISTS products; DROP TABLE IF EXISTS slides; DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS messages; DROP TABLE IF EXISTS content; DROP TABLE IF EXISTS admins;
DROP TABLE IF EXISTS sessions; DROP TABLE IF EXISTS reset_tokens; DROP TABLE IF EXISTS push_subs;
DROP TABLE IF EXISTS notifications; DROP TABLE IF EXISTS media;
CREATE TABLE products (
  id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT UNIQUE NOT NULL, title TEXT NOT NULL,
  description TEXT DEFAULT '', price_pence INTEGER NOT NULL DEFAULT 0, category TEXT DEFAULT 'Gallery',
  images TEXT DEFAULT '[]', stock INTEGER DEFAULT 1, status TEXT DEFAULT 'published', featured INTEGER DEFAULT 0,
  seo_title TEXT DEFAULT '', seo_description TEXT DEFAULT '', etsy_url TEXT DEFAULT '', sort INTEGER DEFAULT 0,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE slides (id INTEGER PRIMARY KEY AUTOINCREMENT, image TEXT NOT NULL, title TEXT DEFAULT '', subtitle TEXT DEFAULT '', link TEXT DEFAULT '', sort INTEGER DEFAULT 0);
CREATE TABLE orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT, number TEXT UNIQUE NOT NULL, email TEXT NOT NULL, name TEXT NOT NULL,
  address TEXT DEFAULT '{}', items TEXT NOT NULL, total_pence INTEGER NOT NULL, status TEXT DEFAULT 'new',
  stripe_session TEXT DEFAULT '', created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE messages (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT, email TEXT, body TEXT, is_read INTEGER DEFAULT 0, created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE content (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE admins (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT UNIQUE NOT NULL, password_hash TEXT DEFAULT '', salt TEXT DEFAULT '', created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE sessions (token_hash TEXT PRIMARY KEY, admin_id INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE reset_tokens (token_hash TEXT PRIMARY KEY, admin_id INTEGER NOT NULL, expires INTEGER NOT NULL, used INTEGER DEFAULT 0);
CREATE TABLE push_subs (endpoint TEXT PRIMARY KEY, p256dh TEXT, auth TEXT, admin_id INTEGER, created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE notifications (id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT, body TEXT, url TEXT DEFAULT '/admin/', created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE media (key TEXT PRIMARY KEY, type TEXT NOT NULL, data TEXT NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE IF NOT EXISTS auth_rate_limits (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS auth_rate_limits_expires ON auth_rate_limits(expires);
